import unittest
import threading
from types import SimpleNamespace
from unittest.mock import patch
from joi.chat import CompanionEngine


class RoutingTests(unittest.TestCase):
    def test_our_recall_network_keeps_its_own_tokenizer_after_vocabulary_growth(self):
        def stub(pieces):
            return SimpleNamespace(tokenizer=SimpleNamespace(kind="word", chars=pieces, stoi={"Arnav": 1}),
                                   model=object(), checkpoint={}, checkpoint_sha256="test", no_repeat_ngram_size=6,
                                   lock=threading.Lock(), lexical_words=["hello"], tokens=64,
                                   temperature=1.0, top_k=15, beams=4)
        general, recall = stub(["new", "vocabulary"]), stub(["old", "vocabulary"])
        with patch("joi.chat.ChatEngine", side_effect=[general, recall]), patch("pathlib.Path.is_file", return_value=True):
            engine = CompanionEngine("our-checkpoint.pt")
        self.assertIs(engine.recall, recall)
        self.assertIs(engine.recall.lock, general.lock)
        self.assertIs(engine.recall.lexical_words, general.lexical_words)
        self.assertNotEqual(engine.recall.tokenizer.chars, general.tokenizer.chars)

    def engine(self):
        class Vocabulary:
            stoi={"Arnav":1,"Sam":2}
        class General:
            tokenizer=Vocabulary()
            def reply(self,messages,**kwargs):
                return {"reply":"Generated by the general network"}
        class Recall:
            def reply(self,messages,**kwargs):
                return {"reply":"Generated by the recall network"}
        result=CompanionEngine.__new__(CompanionEngine)
        result.general,result.recall=General(),Recall()
        return result

    def test_unknown_name_question_selects_neural_specialist_without_writing_answer(self):
        engine=self.engine()
        messages=[{"role":"user","content":"My name is Neel."},
                  {"role":"assistant","content":"Hi there!"},
                  {"role":"user","content":"What is my name?"}]
        result=engine.reply(messages)
        self.assertEqual(result["model_used"],"neural-recall-specialist")
        self.assertEqual(result["reply"],"Generated by the recall network")

    def test_known_name_and_ordinary_conversation_keep_the_general_network(self):
        engine=self.engine()
        for name in ("Arnav","Neel"):
            messages=[{"role":"user","content":f"My name is {name}."},
                      {"role":"assistant","content":"Hi there!"},
                      {"role":"user","content":"What do you think of my project?"}]
            self.assertFalse(engine.uses_recall(messages))
        messages[-1]["content"]="What is my name?"
        messages[0]["content"]="My name is Arnav."
        self.assertEqual(engine.reply(messages)["model_used"],"neural-general-dialogue")


if __name__ == "__main__":
    unittest.main()
