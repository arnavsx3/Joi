import unittest
import threading
from types import SimpleNamespace
from unittest.mock import patch
from pathlib import Path
from tempfile import TemporaryDirectory
from joi.chat import ChatEngine, CompanionEngine, default_checkpoint
from joi.checkpoint import save_checkpoint
from joi.model import Joi, ModelConfig
from joi.tokenizer import WordTokenizer


class RoutingTests(unittest.TestCase):
    def test_packaged_decoding_settings_are_used_and_explicit_overrides_work(self):
        tokenizer = WordTokenizer.from_text("hello", 100)
        model = Joi(ModelConfig(len(tokenizer.chars), block_size=64, n_embd=8, n_heads=2, n_layers=1))
        with TemporaryDirectory() as directory:
            checkpoint = Path(directory) / "model.pt"
            save_checkpoint(checkpoint, model, tokenizer, dataset_manifest={"format": "joi-dialogue-v1"},
                            lexical_words=["hello"], decoding_settings={"temperature":1.0,"top_k":12,"beams":4,"max_new_tokens":64})
            default = ChatEngine(checkpoint)
            self.assertEqual((default.temperature, default.top_k, default.beams, default.tokens), (1.0, 12, 4, 64))
            override = ChatEngine(checkpoint, temperature=0.45, top_k=7, beams=1, tokens=20)
            self.assertEqual((override.temperature, override.top_k, override.beams, override.tokens), (0.45, 7, 1, 20))
            self.assertTrue(default.status()["word_boundary_constraint"])

    def test_default_prefers_packaged_upgrade_and_preserves_legacy_fallback(self):
        with TemporaryDirectory() as directory:
            root = Path(directory)
            legacy = root / "checkpoints/joi-chat/best.pt"
            self.assertEqual(default_checkpoint(root), legacy)
            upgraded = root / "checkpoints/joi-v2/best.pt"
            upgraded.parent.mkdir(parents=True)
            upgraded.touch()
            self.assertEqual(default_checkpoint(root), upgraded)

    def test_our_recall_network_keeps_its_own_tokenizer_after_vocabulary_growth(self):
        def stub(pieces):
            return SimpleNamespace(tokenizer=SimpleNamespace(kind="word", chars=pieces, stoi={"Arnav": 1}),
                                   model=object(), checkpoint={}, checkpoint_sha256="test", no_repeat_ngram_size=6,
                                   lock=threading.Lock(), lexical_words=["hello"], tokens=64,
                                   temperature=1.0, top_k=15, beams=4)
        general, recall = stub(["new", "vocabulary"]), stub(["old", "vocabulary"])
        with patch("joi.chat.ChatEngine", side_effect=[general, recall]), patch("pathlib.Path.is_file", return_value=True):
            engine = CompanionEngine("our-checkpoint.pt")
        self.assertIs(engine.recall, recall)
        self.assertIs(engine.recall.lock, general.lock)
        self.assertIs(engine.recall.lexical_words, general.lexical_words)
        self.assertNotEqual(engine.recall.tokenizer.chars, general.tokenizer.chars)

    def engine(self):
        class Vocabulary:
            stoi={"Arnav":1,"Sam":2}
        class General:
            tokenizer=Vocabulary()
            def reply(self,messages,**kwargs):
                return {"reply":"Generated by the general network"}
        class Recall:
            def reply(self,messages,**kwargs):
                return {"reply":"Generated by the recall network"}
        result=CompanionEngine.__new__(CompanionEngine)
        result.general,result.recall=General(),Recall()
        return result

    def test_unknown_name_question_selects_neural_specialist_without_writing_answer(self):
        engine=self.engine()
        messages=[{"role":"user","content":"My name is Neel."},
                  {"role":"assistant","content":"Hi there!"},
                  {"role":"user","content":"What is my name?"}]
        result=engine.reply(messages)
        self.assertEqual(result["model_used"],"neural-recall-specialist")
        self.assertEqual(result["reply"],"Generated by the recall network")

    def test_optional_earlier_network_preserves_familiar_names_without_substitution(self):
        engine=self.engine()
        class Earlier:
            tokenizer=SimpleNamespace(stoi={"Arnav":1})
            def reply(self,messages,**kwargs):
                return {"reply":"Generated by our earlier network"}
        engine.familiar=Earlier()
        intro=[{"role":"user","content":"My name is Arnav."}]
        self.assertEqual(engine.reply(intro)["reply"],"Generated by our earlier network")
        history=intro+[{"role":"assistant","content":"Hi!"},{"role":"user","content":"What is my name?"}]
        self.assertEqual(engine.reply(history)["model_used"],"neural-familiar-name-dialogue")
        history[-1]["content"]="How was your day?"
        self.assertEqual(engine.reply(history)["reply"],"Generated by the general network")

    def test_known_name_and_ordinary_conversation_keep_the_general_network(self):
        engine=self.engine()
        for name in ("Arnav","Neel"):
            messages=[{"role":"user","content":f"My name is {name}."},
                      {"role":"assistant","content":"Hi there!"},
                      {"role":"user","content":"What do you think of my project?"}]
            self.assertFalse(engine.uses_recall(messages))
        messages[-1]["content"]="What is my name?"
        messages[0]["content"]="My name is Arnav."
        self.assertEqual(engine.reply(messages)["model_used"],"neural-general-dialogue")


if __name__ == "__main__":
    unittest.main()
